"""Reusable UI components. Pure presentation: no ML code in this file."""
import html
from pathlib import Path
import streamlit as st

NAV_COLORS = ["#6366f1", "#a855f7", "#06b6d4", "#10b981", "#f59e0b", "#ec4899", "#ef4444", "#64748b"]
e = lambda x: html.escape(str(x))


def inject_css():
    css = (Path(__file__).with_name("styles.css")).read_text(encoding="utf-8")
    for i, c in enumerate(NAV_COLORS):
        css += (f".st-key-nav_{i} [data-testid='stIconMaterial']{{color:{c};background:{c}1f;"
                f"border-radius:8px;padding:5px;font-size:18px!important}}\n")
    st.markdown(f"<style>{css}</style>", unsafe_allow_html=True)


def header(user: str, status: str) -> bool:
    """Top bar. Returns True when Log Out is clicked."""
    with st.container(key="topbar"):
        c1, c2, c3 = st.columns([1.3, 1.4, 2.3], vertical_alignment="center")
        c1.markdown('<div class="brand"><div class="logo">SH</div><div><b>SmartHire AI</b>'
                    '<small>Career guidance system</small></div></div>', unsafe_allow_html=True)
        c2.markdown('<div class="titleblock">Resume Analysis<br>&amp; Career Guidance'
                    '<small>SMART · HIRE · GROW</small></div>', unsafe_allow_html=True)
        with c3:
            st.markdown(f'<div class="welcome">Welcome! <b>{e(user)}</b> Resume:'
                        f'<span class="pink">{e(status)}</span></div>', unsafe_allow_html=True)
            return st.button("Log Out", icon=":material/logout:", key="logout_top")


def sidebar(pages, active):
    """Sidebar menu. Returns the clicked page name or None."""
    clicked = None
    with st.sidebar:
        st.markdown('<div class="side-head"><span class="side-ico">🎓</span>SmartHire Menu</div>',
                    unsafe_allow_html=True)
        for i, (name, icon) in enumerate(pages):
            if st.button(name, icon=f":material/{icon}:", key=f"nav_{i}", use_container_width=True,
                         type="primary" if name == active else "secondary"):
                clicked = name
    return clicked


def banner(text_html: str):
    st.markdown(f'<div class="banner">{text_html}</div>', unsafe_allow_html=True)


def card():
    return st.container(border=True)


def section(title: str):
    st.markdown(f'<h2 class="sec">{e(title)}</h2>', unsafe_allow_html=True)


def stat(label: str, value: str, pink: bool = False):
    st.markdown(f'<div class="stat"><div class="k">{e(label)}</div>'
                f'<div class="v{" pink" if pink else ""}">{e(value)}</div></div>', unsafe_allow_html=True)


def info_table(rows):
    body = "".join(f"<tr><td>{e(k)}</td><td>{e(v)}</td></tr>" for k, v in rows)
    st.markdown(f'<table class="rows">{body}</table>', unsafe_allow_html=True)


def chips(items, kind="ok", empty="None"):
    if not items:
        st.markdown(f'<div class="empty">{e(empty)}</div>', unsafe_allow_html=True)
        return
    st.markdown("".join(f'<span class="chip {kind}">{e(i)}</span>' for i in items), unsafe_allow_html=True)


def job_list(jobs):
    if not jobs:
        st.markdown('<div class="empty">No recommendations yet.</div>', unsafe_allow_html=True)
        return
    out = ""
    for i, j in enumerate(jobs, 1):
        s = j.get("score")
        pct = f"{s:.1f}%" if s is not None else "n/a"
        w = max(0, min(100, s or 0))
        out += (f'<div class="job"><div class="n">{i}</div><div><div class="t">{e(j["title"])}</div>'
                f'<div class="c">{e(j.get("company") or "")}</div></div><div class="bar-wrap">'
                f'<div class="pct">{pct}</div><div class="bar"><i style="width:{w}%"></i></div></div></div>')
    st.markdown(out, unsafe_allow_html=True)


def activity(items):
    if not items:
        st.markdown('<div class="empty">No activity yet. Upload a resume to begin.</div>', unsafe_allow_html=True)
        return
    st.markdown("".join(f'<div class="act"><span>{e(t)}</span>{e(m)}</div>' for t, m in reversed(items[-6:])),
                unsafe_allow_html=True)


def footer_note():
    with card():
        st.markdown('<div class="note">All results are generated by the SmartHire machine learning models '
                    '(TF-IDF + Logistic Regression, TF-IDF + cosine similarity). They are guidance, not a hiring decision.'
                    '</div>', unsafe_allow_html=True)